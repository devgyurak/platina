"""Agent-neutral edit hook shared by Claude Code, Codex and Pi.

    pre   - block edits to generated agent files (edit the canonical .agents/ source instead)
    post  - run guards + ruff on the edited files and feed violations back to the agent

Input: the hook JSON on stdin (Claude Code / Codex ``PreToolUse``/``PostToolUse`` payloads) or
explicit ``--paths`` (Pi extension). Exit code 2 + stderr is the shared "blocking feedback"
convention of Claude Code and Codex; the Pi extension maps it onto its own API.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from tools.agentsync import GENERATED_PREFIXES  # noqa: E402

_PATCH_FILE = re.compile(
    r"^\*\*\* (?:Add|Update|Delete) File: (.+)$|^\*\*\* Move to: (.+)$", re.MULTILINE
)
_PATH_KEYS = {"file_path", "path", "notebook_path"}
# Keys that carry file *content*. Their text may legitimately contain `*** Update File: ...` and
# must not be read as a patch. Every other string is scanned, whatever its key or nesting
# ({"command": ["apply_patch", patch]}, {"input": patch}, a heredoc inside a shell command):
# the exact payload shape of each agent's patch tool is not something we can pin down.
_CONTENT_KEYS = {"content", "new_string", "old_string", "new_source"}


def extract_paths(payload: Any) -> list[str]:
    """Collect file paths from any tool input shape (Edit/Write, apply_patch, MultiEdit, ...)."""
    found: list[str] = []
    if isinstance(payload, dict):
        for key, value in payload.items():
            if key in _PATH_KEYS and isinstance(value, str):
                found.append(value)
            elif key not in _CONTENT_KEYS:
                found += extract_paths(value)
    elif isinstance(payload, list):
        for item in payload:
            found += extract_paths(item)
    elif isinstance(payload, str):
        found += [a or b for a, b in _PATCH_FILE.findall(payload)]
    return found


def to_repo_relative(raw: str, cwd: Path) -> str | None:
    path = (cwd / raw).resolve() if not Path(raw).is_absolute() else Path(raw).resolve()
    return path.relative_to(ROOT).as_posix() if path.is_relative_to(ROOT) else None


def pre(paths: list[str]) -> int:
    blocked = [p for p in paths if p.startswith(GENERATED_PREFIXES)]
    if not blocked:
        return 0
    print(
        f"Blocked: {', '.join(blocked)} is generated by tools/agentsync.py. Edit the canonical file "
        "under .agents/ (agents/, rules/ or skills/) and run `make agents-sync`.",
        file=sys.stderr,
    )
    return 2


def post(paths: list[str]) -> int:
    existing = [p for p in paths if (ROOT / p).is_file() and not p.startswith(GENERATED_PREFIXES)]
    if not existing:
        return 0
    py = [p for p in existing if p.endswith(".py")]
    reports: list[str] = []
    guard = _run([sys.executable, "-m", "tools.guards", *existing])
    if guard.returncode != 0:
        reports.append(guard.stderr.strip())
    if py:
        ruff = _run(
            [sys.executable, "-m", "ruff", "check", "--quiet", "--output-format=concise", *py]
        )
        if ruff.returncode != 0:
            reports.append(ruff.stdout.strip() or ruff.stderr.strip())
    if not reports:
        return 0
    print(
        "Project guards found problems in the files you just edited - fix them now:\n",
        file=sys.stderr,
    )
    print("\n\n".join(reports), file=sys.stderr)
    return 2


def _run(cmd: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=["pre", "post"])
    parser.add_argument("--paths", nargs="*", help="explicit paths (skip reading stdin)")
    args = parser.parse_args()
    if args.paths is not None:
        raw, cwd = args.paths, Path.cwd()
    else:
        try:
            payload = json.loads(sys.stdin.read() or "{}")
        except json.JSONDecodeError:
            return 0  # never break the agent on an unexpected payload; CI still runs the guards
        raw = extract_paths(payload.get("tool_input", payload))
        cwd = Path(payload.get("cwd") or Path.cwd())
    paths = sorted({p for r in raw if (p := to_repo_relative(r, cwd))})
    return pre(paths) if args.mode == "pre" else post(paths)


if __name__ == "__main__":
    raise SystemExit(main())
