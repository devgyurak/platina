"""Generate per-agent configuration from the canonical, tool-neutral sources in ``.agents/``.

Source of truth                      Generated for
  .agents/skills/<name>/SKILL.md       Codex, Pi: read natively  | Claude Code: .claude/skills/
  .agents/agents/<name>.md             .claude/agents/*.md, .codex/agents/*.toml, .pi/agents/*.md
  .agents/rules/<name>.md              .claude/rules/*.md (path-scoped) + rules index in AGENTS.md

    uv run python -m tools.agentsync           # write
    uv run python -m tools.agentsync --check   # exit 1 on drift (CI, pre-commit)

Canonical agent frontmatter: name, description, access (read-only | review | write), effort
(medium | high). read-only = no shell (Read/Grep/Glob; Codex read-only sandbox); review = shell
for tests and experiments, no file edits by instruction (Codex: workspace-write sandbox); write = all. Canonical rule frontmatter: description, paths (glob list).
"""

from __future__ import annotations

import argparse
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / ".agents"
GENERATED_PREFIXES = (
    ".claude/agents/",
    ".claude/rules/",
    ".claude/skills/",
    ".codex/agents/",
    ".pi/agents/",
)
_BANNER = (
    "GENERATED by tools/agentsync.py from {src} - edit the source, then run `make agents-sync`."
)
_BEGIN, _END = "<!-- agentsync:begin -->", "<!-- agentsync:end -->"

# read-only agents get no shell: a shell can write files and run anything.
_CLAUDE_TOOLS = {
    "read-only": "Read, Grep, Glob",
    "review": "Read, Grep, Glob, Bash",
    "write": None,
}
_CODEX_SANDBOX = {"read-only": "read-only", "review": "workspace-write", "write": "workspace-write"}
_PI_TOOLS = {
    "read-only": "read, grep, find, ls",
    "review": "read, grep, find, ls, bash",
    "write": "read, grep, find, ls, bash, edit, write",
}


@dataclass(frozen=True)
class Doc:
    path: Path
    meta: dict[str, object]
    body: str


def read_doc(path: Path) -> Doc:
    text = path.read_text()
    if not text.startswith("---\n"):
        raise SystemExit(f"{path}: missing YAML frontmatter")
    _, front, body = text.split("---\n", 2)
    return Doc(path, yaml.safe_load(front), body.lstrip("\n"))


def frontmatter(meta: dict[str, object]) -> str:
    return (
        "---\n" + yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=10_000) + "---\n"
    )


def toml_str(value: str) -> str:
    if "'''" not in value:
        return "'''\n" + value + "'''"
    escaped = value.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    return '"""\n' + escaped + '"""'


def desired() -> dict[Path, str]:
    out: dict[Path, str] = {}
    agents = [read_doc(p) for p in sorted((SRC / "agents").glob("*.md"))]
    rules = [read_doc(p) for p in sorted((SRC / "rules").glob("*.md"))]
    skills = sorted(p.parent for p in (SRC / "skills").glob("*/SKILL.md"))

    for a in agents:
        name, desc, access = str(a.meta["name"]), str(a.meta["description"]), str(a.meta["access"])
        effort = str(a.meta.get("effort", "high"))
        banner = _BANNER.format(src=a.path.relative_to(ROOT).as_posix())
        claude_meta: dict[str, object] = {"name": name, "description": desc}
        if tools := _CLAUDE_TOOLS[access]:
            claude_meta["tools"] = tools
        claude_meta["model"] = "inherit"
        out[ROOT / f".claude/agents/{name}.md"] = (
            f"{frontmatter(claude_meta)}\n<!-- {banner} -->\n\n{a.body}"
        )
        out[ROOT / f".pi/agents/{name}.md"] = (
            f"{frontmatter({'name': name, 'description': desc, 'tools': _PI_TOOLS[access]})}\n"
            f"<!-- {banner} -->\n\n{a.body}"
        )
        out[ROOT / f".codex/agents/{name}.toml"] = (
            f"# {banner}\n"
            f"name = {toml_basic(name)}\n"
            f"description = {toml_basic(desc)}\n"
            f'sandbox_mode = "{_CODEX_SANDBOX[access]}"\n'
            f'model_reasoning_effort = "{effort}"\n'
            f"developer_instructions = {toml_str(a.body)}\n"
        )

    for r in rules:
        banner = _BANNER.format(src=r.path.relative_to(ROOT).as_posix())
        meta = {"description": r.meta["description"], "paths": r.meta["paths"]}
        out[ROOT / f".claude/rules/{r.path.name}"] = (
            f"{frontmatter(meta)}\n<!-- {banner} -->\n\n{r.body}"
        )

    for skill_dir in skills:
        for file in sorted(p for p in skill_dir.rglob("*") if p.is_file()):
            out[ROOT / ".claude/skills" / file.relative_to(SRC / "skills")] = file.read_text()

    agents_md = ROOT / "AGENTS.md"
    out[agents_md] = splice(agents_md.read_text(), index_block(agents, rules, skills))
    return out


def toml_basic(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def index_block(agents: list[Doc], rules: list[Doc], skills: list[Path]) -> str:
    lines = [
        _BEGIN,
        "<!-- Generated by tools/agentsync.py. Edit .agents/ and run `make agents-sync`. -->",
        "",
        "### Rules (read the matching rule before editing files under its paths)",
        "",
        "| Rule | Applies to | Summary |",
        "|---|---|---|",
        *(
            f"| [`{r.path.stem}`](.agents/rules/{r.path.name}) | {', '.join(f'`{g}`' for g in _paths(r))} "
            f"| {r.meta['description']} |"
            for r in rules
        ),
        "",
        "### Sub-agents",
        "",
        "| Agent | Access | Use it for |",
        "|---|---|---|",
        *(
            f"| [`{a.meta['name']}`](.agents/agents/{a.path.name}) | {a.meta['access']} | {a.meta['description']} |"
            for a in agents
        ),
        "",
        "### Skills",
        "",
        "| Skill | When |",
        "|---|---|",
        *(
            f"| [`{s.name}`](.agents/skills/{s.name}/SKILL.md) | {read_doc(s / 'SKILL.md').meta['description']} |"
            for s in skills
        ),
        _END,
    ]
    return "\n".join(lines)


def _paths(rule: Doc) -> list[str]:
    paths = rule.meta["paths"]
    if not isinstance(paths, list):
        raise SystemExit(f"{rule.path}: `paths` must be a list of globs")
    return [str(p) for p in paths]


def splice(text: str, block: str) -> str:
    if _BEGIN not in text or _END not in text:
        raise SystemExit(f"AGENTS.md must contain {_BEGIN} ... {_END} markers")
    head, rest = text.split(_BEGIN, 1)
    _, tail = rest.split(_END, 1)
    return head + block + tail


def stale(want: dict[Path, str]) -> list[Path]:
    existing = {
        p for prefix in GENERATED_PREFIXES for p in (ROOT / prefix).rglob("*") if p.is_file()
    }
    return sorted(existing - set(want))


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    want = desired()
    drift = [p for p, c in want.items() if not p.is_file() or p.read_text() != c]
    extra = stale(want)
    if args.check:
        for p in [*drift, *extra]:
            print(f"agentsync: out of date: {p.relative_to(ROOT)}", file=sys.stderr)
        if drift or extra:
            print("agentsync: run `make agents-sync`", file=sys.stderr)
            return 1
        return 0
    for p in drift:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(want[p])
        print(f"wrote   {p.relative_to(ROOT)}")
    for p in extra:
        p.unlink()
        print(f"removed {p.relative_to(ROOT)}")
    for d in sorted({p.parent for p in extra}, reverse=True):
        if d.is_dir() and not any(d.iterdir()):
            shutil.rmtree(d)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
