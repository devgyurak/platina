# --------------------------------------------------------------------------- item 1: renames
def r_column(step: int) -> Callable[[str], sa.MetaData]:
    def build(naming: str) -> sa.MetaData:
        if step == 0:

            class User(Entity, table="users"):
                id: Col[Id[User]] = pk()
                email: Col[str] = column(length=200)
                name: Col[str]

        elif step == 1:

            class User(Entity, table="users"):
                id: Col[Id[User]] = pk()
                contact_email: Col[str] = column(length=200, renamed_from="email")
                name: Col[str]

        else:

            class User(Entity, table="users"):
                id: Col[Id[User]] = pk()
                contact_email: Col[str] = column(length=200, renamed_from="email")
                name: Col[str]
                nickname: Col[str | None]

        return to_metadata(User, naming=naming)

    return build


def r_table(step: int) -> Callable[[str], sa.MetaData]:
    def build(naming: str) -> sa.MetaData:
        if step == 0:

            class User(Entity, table="users"):
                id: Col[Id[User]] = pk()
                email: Col[str] = column(length=200, unique=True)

            class Order(Entity, table="orders"):
                id: Col[Id[Order]] = pk()
                user_id: Col[Id[User]] = fk(lambda: User)

            return to_metadata(User, Order, naming=naming)

        class Customer(Entity, table="customers", renamed_from="users"):
            id: Col[Id[Customer]] = pk()
            email: Col[str] = column(length=200, unique=True)

        class Order(Entity, table="orders"):  # type: ignore[no-redef]
            id: Col[Id[Order]] = pk()
            user_id: Col[Id[Customer]] = fk(lambda: Customer)

        return to_metadata(Customer, Order, naming=naming)

    return build


def r_type(step: int) -> Callable[[str], sa.MetaData]:
    def build(naming: str) -> sa.MetaData:
        if step == 0:

            class Order(Entity, table="orders"):
                id: Col[Id[Order]] = pk()
                number: Col[str] = column(length=20)

        else:

            class Order(Entity, table="orders"):
                id: Col[Id[Order]] = pk()
                order_no: Col[str] = column(length=40, renamed_from="number")

        return to_metadata(Order, naming=naming)

    return build


def r_constrained(step: int) -> Callable[[str], sa.MetaData]:
    def build(naming: str) -> sa.MetaData:
        class User(Entity, table="users"):
            id: Col[Id[User]] = pk()

        if step == 0:

            class Order(Entity, table="orders"):
                id: Col[Id[Order]] = pk()
                user_id: Col[Id[User]] = fk(lambda: User)
                quantity: Col[int]

                class Meta:
                    indexes = (Index(lambda: (Order.user_id,)),)
                    checks = (Check(lambda: Order.quantity > 0),)

        else:

            class Order(Entity, table="orders"):
                id: Col[Id[Order]] = pk()
                customer_id: Col[Id[User]] = fk(lambda: User, renamed_from="user_id")
                qty: Col[int] = column(renamed_from="quantity")

                class Meta:
                    indexes = (Index(lambda: (Order.customer_id,)),)
                    checks = (Check(lambda: Order.qty > 0),)

        return to_metadata(User, Order, naming=naming)

    return build


# --------------------------------------------------------------------------- items 2 and 6: checks
def checks(step: int) -> Callable[[str], sa.MetaData]:
    def build(naming: str) -> sa.MetaData:
        order_checks = {
            0: lambda: Order.total.path(Money.amount) >= Decimal(0),
            1: lambda: Order.total.path(Money.amount) >= Decimal(0),
            2: lambda: Order.total.path(Money.amount) > Decimal(0),
            3: lambda: Order.total.path(Money.amount) > Decimal(0),
        }[step]

        class Order(Entity, table="orders"):
            id: Col[Id[Order]] = pk()
            total: Col[Money] = embedded(prefix="total_")

            class Meta:
                checks = (Check(order_checks),)

        stock_checks = (Check(lambda: Stock.allocated <= Stock.quantity),) if step in (1, 2) else ()

        class Stock(Entity, table="stock"):
            id: Col[Id[Stock]] = pk()
            quantity: Col[int]
            allocated: Col[int]

            class Meta:
                checks = stock_checks

        return to_metadata(Order, Stock, naming=naming)

    return build


def uniques(step: int) -> Callable[[str], sa.MetaData]:
    def build(naming: str) -> sa.MetaData:
        stock_uniques = (
            (Unique(lambda: (Stock.warehouse_id, Stock.variant_id)),) if step == 1 else ()
        )

        class Stock(Entity, table="stock"):
            id: Col[Id[Stock]] = pk()
            warehouse_id: Col[Id[object]]
            variant_id: Col[Id[object]]
            quantity: Col[int]

            class Meta:
                uniques = stock_uniques

        return to_metadata(Stock, naming=naming)

    return build


# --------------------------------------------------------------------------- item 3: triggers
def triggers(step: int) -> Callable[[str], sa.MetaData]:
    """0: Order versioned; 1: User gains version; 2: body changed; 3: Order loses it; 4: none."""

    def build(naming: str) -> sa.MetaData:
        order_versioned = step <= 2
        user_versioned = 1 <= step <= 3
        body = VERSION_BODY_V2 if step >= 2 else VERSION_BODY_V1

        if order_versioned:

            class Order(Entity, table="orders"):
                id: Col[Id[Order]] = pk()
                number: Col[str] = column(length=20)
                version: Col[int] = version_column()

        else:

            class Order(Entity, table="orders"):  # type: ignore[no-redef]
                id: Col[Id[Order]] = pk()
                number: Col[str] = column(length=20)

        if user_versioned:

            class User(Entity, table="users"):
                id: Col[Id[User]] = pk()
                email: Col[str] = column(length=200)
                version: Col[int] = version_column()

        else:

            class User(Entity, table="users"):  # type: ignore[no-redef]
                id: Col[Id[User]] = pk()
                email: Col[str] = column(length=200)

        return to_metadata(Order, User, naming=naming, version_body=body)

    return build


# --------------------------------------------------------------------------- item 4: indexes
def indexes(step: int) -> Callable[[str], sa.MetaData]:
    """0: as declared; 1: function expression changed; 2: WHERE changed; 3: desc() removed."""

    def build(naming: str) -> sa.MetaData:
        email_expr = (
            (lambda: (fn.lower(User.email),))
            if step == 0
            else (lambda: (fn.lower(fn.btrim(User.email)),))
        )
        pending_where = (
            (lambda: Order.status == OrderStatus.PENDING)
            if step <= 1
            else (lambda: Order.status == OrderStatus.PAID)
        )
        user_created = (
            (lambda: (Order.user_id, Order.created_at.desc()))
            if step <= 2
            else (lambda: (Order.user_id, Order.created_at))
        )

        class User(Entity, table="users"):
            id: Col[Id[User]] = pk()
            email: Col[str] = column(length=200)

            class Meta:
                indexes = (Index(email_expr, unique=True),)

        class Order(Entity, table="orders"):
            id: Col[Id[Order]] = pk()
            user_id: Col[Id[User]] = fk(lambda: User)
            status: Col[OrderStatus]
            created_at: Col[datetime] = column(server_default=server_now())

            class Meta:
                indexes = (
                    Index(user_created),
                    Index(lambda: (Order.created_at,), where=pending_where),
                )

        return to_metadata(User, Order, naming=naming)

    return build


# --------------------------------------------------------------------------- item 5: internal tables
def internal(step: int) -> Callable[[str], sa.MetaData]:
    """0: the five tables; 1: outbox gains a column and an index; 2 (dry): run_claim re-keyed."""

    def build(naming: str) -> sa.MetaData:
        claim_partition = "RANGE (id)" if step < 2 else "HASH (id)"

        class RunClaim(Entity, table="platina_run_claim", partition_by=claim_partition):
            id: Col[Id[object]] = pk()

        class RunResult(Entity, table="platina_run_result"):
            run_id: Col[Id[object]] = pk()
            result: Col[Json]
            created_at: Col[datetime] = column(server_default=server_now())

        if step == 0:

            class Outbox(Entity, table="platina_outbox", partition_by="RANGE (created_at)"):
                created_at: Col[datetime] = column(primary_key=True)
                xid: Col[Xid8] = column(primary_key=True)
                seq: Col[int] = column(primary_key=True)
                aggregate_type: Col[str]
                aggregate_id: Col[Id[object]]
                payload: Col[Json]

        else:

            class Outbox(Entity, table="platina_outbox", partition_by="RANGE (created_at)"):  # type: ignore[no-redef]
                created_at: Col[datetime] = column(primary_key=True)
                xid: Col[Xid8] = column(primary_key=True)
                seq: Col[int] = column(primary_key=True)
                aggregate_type: Col[str]
                aggregate_id: Col[Id[object]]
                payload: Col[Json]
                headers: Col[Json | None]

                class Meta:
                    indexes = (Index(lambda: (Outbox.aggregate_id,)),)

        class Job(Entity, table="platina_job_send_receipt"):
            id: Col[Id[object]] = pk()
            aggregate_key: Col[str]
            payload: Col[Json]
            lease_until: Col[datetime | None]
            attempts: Col[int] = column(server_default="0")

        class Checkpoint(Entity, table="platina_checkpoint"):
            consumer: Col[str] = column(primary_key=True)
            xid: Col[Xid8]

        return to_metadata(RunClaim, RunResult, Outbox, Job, Checkpoint, naming=naming)

    return build


