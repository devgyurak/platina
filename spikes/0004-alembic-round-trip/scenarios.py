"""Spike 0004: scenarios. Each is a list of states; each state defines its entities from scratch.

`after` SQL (rows) runs after the state's upgrade in `public`. `world` SQL (DDL outside
migrations, e.g. partitions made by a maintenance job) runs after it in `public` and,
cumulatively, in every later reference schema. `probe` SQL runs in `public` and is printed.
`dry_only` states are only autogenerated (dry run), never applied.
"""

from collections.abc import Callable
from dataclasses import dataclass, field
from datetime import datetime
from decimal import Decimal
from enum import Enum

import sqlalchemy as sa
from registry import (
    VERSION_BODY_V1,
    VERSION_BODY_V2,
    Check,
    Col,
    Entity,
    Id,
    Index,
    Json,
    Unique,
    Xid8,
    column,
    embedded,
    fk,
    fn,
    pk,
    server_now,
    to_metadata,
    value,
    version_column,
)


@dataclass
class State:
    label: str
    build: Callable[[str], sa.MetaData]
    after: list[str] = field(default_factory=list)  # rows, `public` only
    world: list[str] = field(default_factory=list)  # DDL outside migrations (both schemas)
    probe: list[str] = field(default_factory=list)
    dry_only: bool = False


@dataclass
class Scenario:
    name: str
    item: str
    states: list[State]
    namings: tuple[str, ...] = ("columns",)


class OrderStatus(Enum):
    PENDING = "pending"
    PAID = "paid"
    CANCELLED = "cancelled"


@value
class Money:
    amount: Col[Decimal]
    currency: Col[str] = column(length=3)


